// Extracts the handful of Flaticon UIcons (Regular Straight) glyphs the site uses
// from the official @flaticon/flaticon-uicons webfont into a typed path map, so we
// ship ~15 icons inline instead of the 300 KB font.
// Licence: Flaticon License (free with attribution). Credit lives in the site footer.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const fontkit = require("fontkit");

const pkg = path.dirname(require.resolve("@flaticon/flaticon-uicons/package.json"));
const cssDir = path.join(pkg, "css");
const fontFile = fs.readdirSync(cssDir).find((f) => /^uicons-regular-straight-.*\.woff2$/.test(f));
const css = fs.readFileSync(path.join(cssDir, "regular", "straight.css"), "utf8");
const font = fontkit.openSync(path.join(cssDir, fontFile));

const ICONS = [
  "phone-call", "envelope", "marker", "clock-three", "arrow-right", "arrow-small-right",
  "arrow-up-right", "calendar", "users", "bed-alt", "angle-left", "angle-right",
  "angle-small-down", "cross-small", "play", "volume", "volume-mute", "plus", "expand",
  "building", "wifi", "tv-music", "snowflake", "shield-check", "washer", "shower",
  "parking", "tree", "headset", "bell-concierge", "vacuum", "sofa", "home", "minus-small", "plus-small",
];

const upm = font.unitsPerEm;
const out = {};
for (const name of ICONS) {
  const m = css.match(new RegExp(`\\.fi-rs-${name}:before\\{content:"\\\\([0-9a-f]+)"`));
  if (!m) throw new Error(`Icon not found in UIcons: ${name}`);
  const glyph = font.glyphForCodePoint(parseInt(m[1], 16));
  // Font space is y-up; flip into a 0..upm SVG box.
  const d = glyph.path.scale(1, -1).translate(0, font.ascent).toSVG();
  out[name] = d;
}

const file = `// Generated by scripts/extract-icons.mjs from @flaticon/flaticon-uicons (Regular Straight).
// Do not edit by hand. Icons by Flaticon (flaticon.com/uicons), used under the Flaticon License.
export const ICON_VIEWBOX = "0 0 ${upm} ${upm}";
export const ICON_PATHS = ${JSON.stringify(out, null, 2)} as const;
export type IconName = keyof typeof ICON_PATHS;
`;
fs.mkdirSync("src/components/icons", { recursive: true });
fs.writeFileSync("src/components/icons/paths.ts", file);
console.log(`Wrote ${ICONS.length} icons, upm=${upm}, ascent=${font.ascent}, descent=${font.descent}`);
